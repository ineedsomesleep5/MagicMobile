#!/usr/bin/env python3
"""The web engine's build identity: never the phone engine's (docs/WEB_ENGINE_M1.md, "Engine identity").

The phone identity (packages/ondevice-engine/scripts/engine_build_identity.py) covers the adapter sources, the
upstream pin and its patch scripts. The web build changes the engine's behaviour beyond those (an inline AI search
on one thread, other stop checks), so it hashes the phone identity together with every web-only input: the
rewriter, the web sources, the build script (its native-image options), the builder patch and the toolchain. Ranked
rows must name this value, never the phone's.

    web_identity.py --toolchain "<native-image --version first line>" --output <generated Java source root>
"""
import argparse, hashlib, importlib.util
from pathlib import Path

HERE = Path(__file__).resolve().parent
ENGINE = HERE.parent / 'ondevice-engine'
WEB_INPUTS = ('web_sources.py', 'web_identity.py', 'build_web.sh', 'builder-patch', 'src', 'src-svm')


def phone_identity() -> str:
    spec = importlib.util.spec_from_file_location('engine_build_identity', ENGINE / 'scripts/engine_build_identity.py')
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module.identity()


def identity(toolchain: str) -> str:
    value = hashlib.sha256()
    value.update(b'magicmobile-web-1\0' + phone_identity().encode() + b'\0' + toolchain.encode() + b'\0')
    paths = []
    for name in WEB_INPUTS:
        path = HERE / name
        paths += [p for p in path.rglob('*') if p.is_file()] if path.is_dir() else [path]
    for path in sorted(paths, key=lambda p: p.relative_to(HERE).as_posix()):
        data = path.read_bytes()
        value.update(path.relative_to(HERE).as_posix().encode() + b'\0' + str(len(data)).encode() + b'\0' + data)
    return 'web-1:sha256:' + value.hexdigest()


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--toolchain', required=True)
    parser.add_argument('--output', type=Path, required=True)
    args = parser.parse_args()
    target = args.output / 'io/magicmobile/generated/EngineBuildIdentity.java'
    target.parent.mkdir(parents=True, exist_ok=True)
    value = identity(args.toolchain)
    target.write_text('package io.magicmobile.generated;\n\n'
                      '/** Generated by packages/web-engine/web_identity.py: the web engine, never a phone build. */\n'
                      'public final class EngineBuildIdentity {\n'
                      f'    public static final String VALUE="{value}";\n'
                      '    private EngineBuildIdentity() {}\n}\n')
    print('Web engine build identity', value)


if __name__ == '__main__':
    main()

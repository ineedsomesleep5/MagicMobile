package mage.cards;

import mage.ObjectColor;
import mage.cards.repository.CardInfo;
import mage.collation.BoosterCollator;
import mage.constants.Rarity;
import mage.constants.SetType;
import java.io.BufferedReader;
import java.io.IOException;
import java.io.InputStream;
import java.io.InputStreamReader;
import java.nio.charset.StandardCharsets;
import java.util.*;
import java.util.zip.GZIPInputStream;

/**
 * An XMage set read from the bundled set catalogue (mage/mobile/set-catalogue.tsv.gz, written by
 * RegistryExporter from the real set classes) instead of constructing its Mage.Sets class. It has the
 * class's field values and, through an index over all printings, its card list in the same order; it
 * holds no SetCardInfo objects. A set whose class overrides booster generation passes booster requests
 * to that class, created on first use (Booster Tutor), so packs are generated by the same code.
 */
public final class MobileExpansionSet extends ExpansionSet {
    private static final long serialVersionUID = 1L;
    static final String RESOURCE = "/mage/mobile/set-catalogue.tsv.gz";
    static final String HEADER = "magicmobile-set-catalogue";
    static final int FORMAT = 1;
    /** Set columns after the set's class name, in RegistryExporter's order. */
    static final List<String> FIELDS = List.of("code", "name", "releaseDate", "setType", "blockName", "parentSet",
            "hasBasicLands", "rotationSet", "hasBoosters", "numBoosterSpecial", "numBoosterLands",
            "ratioBoosterSpecialLand", "ratioBoosterSpecialLandNumerator", "ratioBoosterSpecialCommon",
            "ratioBoosterSpecialRare", "ratioBoosterSpecialMythic", "numBoosterCommon", "numBoosterUncommon",
            "numBoosterRare", "numBoosterDoubleFaced", "ratioBoosterMythic", "hasUnbalancedColors",
            "hasOnlyMulticolorCards", "hasAlternateBoosterPrintings", "maxCardNumberInBooster", "customBooster");
    private static final String NULL = "-";

    /** Creates the real set class of a set with custom booster generation (generated, build-time inventory). */
    public interface BoosterSets { ExpansionSet create(String code); }
    private static volatile BoosterSets boosterSets;

    private final String className;
    private final boolean customBooster;
    private final int index;
    private transient ExpansionSet booster;

    private MobileExpansionSet(int index, String className, String[] values) {
        super(values[1], values[0], date(values[2]), SetType.valueOf(values[3]));
        this.index = index;
        this.className = className;
        blockName = text(values[4]);
        hasBasicLands = flag(values[6]);
        rotationSet = flag(values[7]);
        hasBoosters = flag(values[8]);
        numBoosterSpecial = Integer.parseInt(values[9]);
        numBoosterLands = Integer.parseInt(values[10]);
        ratioBoosterSpecialLand = Integer.parseInt(values[11]);
        ratioBoosterSpecialLandNumerator = Integer.parseInt(values[12]);
        ratioBoosterSpecialCommon = Integer.parseInt(values[13]);
        ratioBoosterSpecialRare = Double.parseDouble(values[14]);
        ratioBoosterSpecialMythic = Double.parseDouble(values[15]);
        numBoosterCommon = Integer.parseInt(values[16]);
        numBoosterUncommon = Integer.parseInt(values[17]);
        numBoosterRare = Integer.parseInt(values[18]);
        numBoosterDoubleFaced = Integer.parseInt(values[19]);
        ratioBoosterMythic = Double.parseDouble(values[20]);
        hasUnbalancedColors = flag(values[21]);
        hasOnlyMulticolorCards = flag(values[22]);
        hasAlternateBoosterPrintings = flag(values[23]);
        maxCardNumberInBooster = Integer.parseInt(values[24]);
        customBooster = flag(values[25]);
    }

    /**
     * Reads every set, in the order the old generated registry added the set classes (so Sets, a HashMap,
     * iterates them in the same order), with parent sets linked. Printings are read on first use.
     */
    public static List<MobileExpansionSet> load(String registryHash, BoosterSets factory) {
        boosterSets = Objects.requireNonNull(factory);
        try (BufferedReader input = resource()) {
            String[] header = header(input);
            if (!registryHash.equals(header[2])) throw new IOException("Set catalogue is from another card registry");
            int[] counts = counts(header);
            List<MobileExpansionSet> sets = new ArrayList<>(counts[0]);
            List<String> parents = new ArrayList<>(counts[0]);
            Map<String, MobileExpansionSet> byCode = new HashMap<>();
            for (String line; (line = input.readLine()) != null && !line.startsWith("P\t");) {
                if (line.startsWith("G\t")) continue;
                String[] columns = line.split("\t", -1);
                if (!columns[0].equals("S") || columns.length != FIELDS.size() + 2)
                    throw new IOException("Malformed set row: " + line);
                MobileExpansionSet set = new MobileExpansionSet(sets.size(), columns[1],
                        Arrays.copyOfRange(columns, 2, columns.length));
                if (byCode.put(set.getCode(), set) != null) throw new IOException("Repeated set code: " + set.getCode());
                sets.add(set);
                parents.add(text(columns[7]));
            }
            if (sets.size() != counts[0]) throw new IOException("Incomplete set inventory");
            for (int i = 0; i < sets.size(); i++) {
                if (parents.get(i) == null) continue;
                MobileExpansionSet parent = byCode.get(parents.get(i));
                if (parent == null) throw new IOException("Unknown parent set: " + parents.get(i));
                sets.get(i).parentSet = parent;
            }
            return sets;
        } catch (IOException failure) {
            throw new IllegalStateException("Cannot load the bundled XMage set catalogue", failure);
        }
    }

    /** The XMage set class this set was exported from. */
    public String getClassName() { return className; }

    /** True when the set class overrides booster generation, which then runs in that class. */
    public boolean hasCustomBooster() { return customBooster; }

    /** One printing of the catalogue: a set's SetCardInfo without its card class object. */
    public static final class Printing {
        private final int index;
        private Printing(int index) { this.index = index; }
        public String getName() { return Printings.NAME[index]; }
        public String getCardNumber() { return Printings.NUMBER[index]; }
        public Rarity getRarity() { return Printings.RARITIES[Printings.RARITY[index]]; }
        public String getClassName() { return Printings.CLASS[index]; }
        public CardGraphicInfo getGraphicInfo() { return Printings.GRAPHICS[Printings.GRAPHIC[index]]; }
        public CardSetInfo setInfo(String setCode) {
            return new CardSetInfo(getName(), setCode, getCardNumber(), getRarity(), getGraphicInfo());
        }
    }

    /** This set's printings with this collector number, in the set's order (empty for an unknown number). */
    public List<Printing> printings(String cardNumber) {
        List<Printing> result = new ArrayList<>(1);
        for (int i = Printings.START[index], end = Printings.START[index + 1]; i < end; i++)
            if (Printings.NUMBER[i].equals(cardNumber)) result.add(new Printing(i));
        return result;
    }

    /** Whether the set lists any printing (a set class with an empty card list exports none). */
    public boolean hasPrintings() { return Printings.START[index] < Printings.START[index + 1]; }

    /**
     * The set's card list, built from the catalogue on each call. Mobile engine code uses
     * {@link #printings(String)} and {@link #findCardInfoByClass(Class)} instead, which load no card classes.
     */
    @Override
    public List<SetCardInfo> getSetCardInfo() {
        List<SetCardInfo> result = new ArrayList<>(Printings.START[index + 1] - Printings.START[index]);
        try {
            // Not initialized, like the class literals of the set classes' card lists.
            for (int i = Printings.START[index], end = Printings.START[index + 1]; i < end; i++)
                result.add(info(i, Class.forName(Printings.CLASS[i], false, MobileExpansionSet.class.getClassLoader())));
        } catch (ClassNotFoundException failure) {
            throw new IllegalStateException("Catalogue names a missing card class", failure);
        }
        return result;
    }

    /** Same result as upstream's search of the set's card list (CardImpl's second faces, Sets.findCardByClass). */
    @Override
    public List<SetCardInfo> findCardInfoByClass(Class<?> clazz) {
        String name = clazz.getName();
        List<SetCardInfo> result = new ArrayList<>(1);
        for (int i = Printings.START[index], end = Printings.START[index + 1]; i < end; i++)
            if (Printings.CLASS[i].equals(name)) result.add(info(i, clazz));
        return result;
    }

    private static SetCardInfo info(int i, Class<?> cardClass) {
        return new SetCardInfo(Printings.NAME[i], Printings.NUMBER[i], Printings.RARITIES[Printings.RARITY[i]],
                cardClass, Printings.GRAPHICS[Printings.GRAPHIC[i]]);
    }

    private ExpansionSet booster() {
        ExpansionSet result = booster;
        if (result == null) {
            result = boosterSets.create(code);
            if (result == null || !result.getClass().getName().equals(className))
                throw new IllegalStateException("No booster set class for " + code);
            booster = result;
        }
        return result;
    }

    // Booster generation that the set class overrides runs in that class. getCardsByRarity and
    // getSpecialCardsByRarity are final; their find* steps are what child sets reach through parentSet.
    @Override
    public List<Card> create15CardBooster() {
        return customBooster ? booster().create15CardBooster() : super.create15CardBooster();
    }

    @Override
    public List<Card> createBooster() {
        return customBooster ? booster().createBooster() : super.createBooster();
    }

    @Override
    public BoosterCollator createCollator() {
        return customBooster ? booster().createCollator() : super.createCollator();
    }

    @Override
    protected List<CardInfo> findCardsByRarity(Rarity rarity) {
        return customBooster ? booster().findCardsByRarity(rarity) : super.findCardsByRarity(rarity);
    }

    @Override
    protected List<CardInfo> findSpecialCardsByRarity(Rarity rarity) {
        return customBooster ? booster().findSpecialCardsByRarity(rarity) : super.findSpecialCardsByRarity(rarity);
    }

    /** Every printing of every set in catalogue order, as parallel arrays. */
    private static final class Printings {
        static final Rarity[] RARITIES = Rarity.values();
        static CardGraphicInfo[] GRAPHICS;
        static int[] START;
        static String[] NUMBER, NAME, CLASS;
        static byte[] RARITY, GRAPHIC;
        static {
            try (BufferedReader input = resource()) {
                int[] counts = counts(header(input));
                List<CardGraphicInfo> graphics = new ArrayList<>();
                graphics.add(null); // index 0: no graphic info
                Map<String, Integer> setIndex = new HashMap<>();
                Map<String, String> strings = new HashMap<>();
                START = new int[counts[0] + 1];
                NUMBER = new String[counts[1]];
                NAME = new String[counts[1]];
                CLASS = new String[counts[1]];
                RARITY = new byte[counts[1]];
                GRAPHIC = new byte[counts[1]];
                int set = -1, row = 0;
                for (String line; (line = input.readLine()) != null;) {
                    String[] columns = line.split("\t", -1);
                    switch (columns[0]) {
                        case "G":
                            if (columns.length != 5 || Integer.parseInt(columns[1]) != graphics.size())
                                throw new IOException("Malformed graphic row: " + line);
                            graphics.add(new CardGraphicInfo(columns[4].equals(NULL) ? null : new ObjectColor(columns[4]),
                                    columns[2].equals(NULL) ? null : FrameStyle.valueOf(columns[2]), flag(columns[3])));
                            break;
                        case "S":
                            setIndex.put(columns[2], setIndex.size());
                            break;
                        case "P": {
                            if (columns.length != 7) throw new IOException("Malformed printing row: " + line);
                            Integer owner = setIndex.get(columns[1]);
                            if (owner == null || owner < set || row == counts[1]) throw new IOException("Printing out of order: " + line);
                            while (set < owner) START[++set] = row;
                            NUMBER[row] = strings.computeIfAbsent(columns[2], value -> value);
                            NAME[row] = strings.computeIfAbsent(columns[3], value -> value);
                            RARITY[row] = (byte) Rarity.valueOf(columns[4]).ordinal();
                            // Interned: the card factory's name tables hold the same constants.
                            CLASS[row] = columns[5].intern();
                            int graphic = Integer.parseInt(columns[6]);
                            if (graphic < 0 || graphic >= graphics.size()) throw new IOException("Unknown graphic: " + line);
                            GRAPHIC[row] = (byte) graphic;
                            row++;
                            break;
                        }
                        default:
                            throw new IOException("Unknown set catalogue row: " + line);
                    }
                }
                if (setIndex.size() != counts[0] || row != counts[1] || graphics.size() != counts[2] + 1)
                    throw new IOException("Incomplete printing inventory");
                while (set < counts[0]) START[++set] = row;
                GRAPHICS = graphics.toArray(new CardGraphicInfo[0]);
            } catch (IOException | RuntimeException failure) {
                throw new IllegalStateException("Cannot load the bundled XMage printings", failure);
            }
        }
    }

    private static BufferedReader resource() throws IOException {
        InputStream stream = MobileExpansionSet.class.getResourceAsStream(RESOURCE);
        if (stream == null) throw new IOException("Missing bundled XMage set catalogue: " + RESOURCE);
        try {
            return new BufferedReader(new InputStreamReader(new GZIPInputStream(stream), StandardCharsets.UTF_8));
        } catch (IOException failure) {
            stream.close();
            throw failure;
        }
    }

    /** The header line: format, card registry hash, then the numbers of sets, printings and graphic infos. */
    private static String[] header(BufferedReader input) throws IOException {
        String[] columns = String.valueOf(input.readLine()).split("\t", -1);
        if (columns.length != 6 || !columns[0].equals(HEADER) || Integer.parseInt(columns[1]) != FORMAT)
            throw new IOException("Unknown set catalogue format");
        return columns;
    }

    private static int[] counts(String[] header) {
        return new int[]{Integer.parseInt(header[3]), Integer.parseInt(header[4]), Integer.parseInt(header[5])};
    }

    private static Date date(String value) {
        String[] parts = value.split("-", -1);
        return buildDate(Integer.parseInt(parts[0]), Integer.parseInt(parts[1]), Integer.parseInt(parts[2]));
    }

    private static String text(String value) { return value.equals(NULL) ? null : value; }

    private static boolean flag(String value) {
        if (value.equals("1")) return true;
        if (value.equals("0")) return false;
        throw new IllegalArgumentException("Not a flag: " + value);
    }
}
